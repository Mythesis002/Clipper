-- Clipper scheduler Phase 1. PostgreSQL is the source of truth for schedules,
-- slots, jobs, leases, and publishing audit. Apply with:
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f migrations/001_scheduler.sql
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS schema_migrations (
    version text PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email text NOT NULL,
    tz text NOT NULL,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','paused','disabled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS connected_accounts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    platform text NOT NULL CHECK (platform IN ('instagram','youtube')),
    external_id text NOT NULL,
    token_ciphertext bytea,
    token_expires_at timestamptz,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','reconnect_needed','paused','disabled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, platform, external_id),
    UNIQUE (id, user_id)
);

CREATE TABLE IF NOT EXISTS sources (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    youtube_handle text NOT NULL,
    permission_attested boolean NOT NULL DEFAULT false,
    attested_at timestamptz,
    attestation_text text,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','paused','disabled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (permission_attested = false OR (attested_at IS NOT NULL AND length(trim(coalesce(attestation_text,''))) > 0)),
    UNIQUE (user_id, youtube_handle),
    UNIQUE (id, user_id)
);

CREATE TABLE IF NOT EXISTS schedule_rules (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id uuid NOT NULL,
    weekday smallint NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    local_time time NOT NULL,
    active boolean NOT NULL DEFAULT true,
    max_late_minutes integer NOT NULL DEFAULT 20 CHECK (max_late_minutes BETWEEN 0 AND 1440),
    assignment_lead_minutes integer NOT NULL DEFAULT 360 CHECK (assignment_lead_minutes BETWEEN 10 AND 10080),
    verify_lead_minutes integer NOT NULL DEFAULT 30 CHECK (verify_lead_minutes BETWEEN 1 AND 1440),
    container_lead_minutes integer NOT NULL DEFAULT 10 CHECK (container_lead_minutes BETWEEN 1 AND 1440),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (account_id, user_id) REFERENCES connected_accounts(id, user_id) ON DELETE CASCADE,
    UNIQUE (account_id, weekday, local_time)
);

CREATE TABLE IF NOT EXISTS clips (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    source_video_id text NOT NULL,
    start_seconds double precision NOT NULL CHECK (start_seconds >= 0),
    end_seconds double precision NOT NULL CHECK (end_seconds > start_seconds),
    score double precision,
    status text NOT NULL DEFAULT 'queued',
    storage_key text,
    qa_report jsonb NOT NULL DEFAULT '{}'::jsonb,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, id)
);
CREATE INDEX IF NOT EXISTS clips_ready_pick_idx
    ON clips(user_id, status, score DESC NULLS LAST, id);

CREATE TABLE IF NOT EXISTS slots (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id uuid NOT NULL,
    local_date date NOT NULL,
    local_time time NOT NULL,
    tz_snapshot text NOT NULL,
    run_at_utc timestamptz NOT NULL,
    state text NOT NULL DEFAULT 'scheduled' CHECK (state IN (
      'scheduled','assigned','preparing','verified','container_uploading',
      'container_ready','publishing','published','publish_uncertain',
      'missed','failed','cancelled'
    )),
    clip_id bigint,
    container_id text,
    media_id text,
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    lease_owner text,
    lease_until timestamptz,
    publish_started_at timestamptz,
    published_at timestamptz,
    max_late_minutes integer NOT NULL DEFAULT 20 CHECK (max_late_minutes >= 0),
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (account_id, user_id) REFERENCES connected_accounts(id, user_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id, clip_id) REFERENCES clips(user_id, id) DEFERRABLE INITIALLY DEFERRED,
    UNIQUE (account_id, local_date, local_time)
);
CREATE INDEX IF NOT EXISTS slots_dispatch_idx
    ON slots(state, run_at_utc);
CREATE INDEX IF NOT EXISTS slots_account_due_idx
    ON slots(account_id, run_at_utc) WHERE state IN ('container_ready','publishing');

CREATE TABLE IF NOT EXISTS jobs (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    kind text NOT NULL CHECK (kind IN ('prepare_clip','verify_slot','upload_container','produce','youtube_upload')),
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','leased','succeeded','retry','failed','cancelled')),
    priority integer NOT NULL DEFAULT 100,
    run_after timestamptz NOT NULL DEFAULT now(),
    lease_owner text,
    lease_until timestamptz,
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts integer NOT NULL DEFAULT 5 CHECK (max_attempts >= 1),
    dedupe_key text,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS jobs_claim_idx ON jobs(state, run_after, priority, created_at);
CREATE UNIQUE INDEX IF NOT EXISTS jobs_dedupe_idx ON jobs(user_id, dedupe_key) WHERE dedupe_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS events (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    slot_id uuid REFERENCES slots(id) ON DELETE SET NULL,
    ts timestamptz NOT NULL DEFAULT now(),
    type text NOT NULL,
    detail jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS events_slot_ts_idx ON events(slot_id, ts DESC);

CREATE TABLE IF NOT EXISTS state_meta (
    user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    revision bigint NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS scheduler_control (
    key text PRIMARY KEY,
    last_run_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS dispatcher_heartbeats (
    dispatcher_id text PRIMARY KEY,
    ts timestamptz NOT NULL DEFAULT now(),
    detail jsonb NOT NULL DEFAULT '{}'::jsonb
);

-- Events are append-only, including for the application role.
CREATE OR REPLACE FUNCTION clipper_reject_event_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'events is append-only';
END $$;
DROP TRIGGER IF EXISTS events_no_update_delete ON events;
CREATE TRIGGER events_no_update_delete
BEFORE UPDATE OR DELETE ON events FOR EACH ROW
EXECUTE FUNCTION clipper_reject_event_mutation();

-- Tenant RLS. The backend sets app.user_id transaction-locally. Supabase service
-- roles may bypass RLS; never expose a service-role credential to client code.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE connected_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE sources ENABLE ROW LEVEL SECURITY;
ALTER TABLE schedule_rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE clips ENABLE ROW LEVEL SECURITY;
ALTER TABLE slots ENABLE ROW LEVEL SECURITY;
ALTER TABLE jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE events ENABLE ROW LEVEL SECURITY;
ALTER TABLE state_meta ENABLE ROW LEVEL SECURITY;

DO $policy$
DECLARE t text;
BEGIN
  DROP POLICY IF EXISTS tenant_isolation ON users;
  CREATE POLICY tenant_isolation ON users USING (id = nullif(current_setting('app.user_id', true), '')::uuid) WITH CHECK (id = nullif(current_setting('app.user_id', true), '')::uuid);
  FOREACH t IN ARRAY ARRAY['connected_accounts','sources','schedule_rules','clips','slots','jobs','events','state_meta']
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', t);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON %I USING (user_id = nullif(current_setting(''app.user_id'', true), '''')::uuid) WITH CHECK (user_id = nullif(current_setting(''app.user_id'', true), '''')::uuid)',
      t
    );
  END LOOP;
END $policy$;

